#!/usr/bin/env python3
"""Generate libutf's collation tables: DUCET plus CLDR locale tailorings.

Outputs (paths relative to this script):
  ../tables/ducet_dfa_tables.c  tr_ducet (code point -> CE index) and
                                tr_ducet_contract (two code points -> CE
                                index), each one shared pool holding every
                                collator's machine
  ../tables/ducet_cetable.c     CE weights and offsets, longer contractions,
                                Latin fast-path tables, reorder ranges,
                                tertiary maps and the collator registry
  ../include/utf/utf_tables.h   the DUCET section, between its markers
  data/tr_ducet.txt             root only, for the C++ builders (TinyMUX)
  data/tr_ducet_contract.txt

Inputs: data/allkeys.txt (DUCET), data/UnicodeData.txt, data/Scripts.txt and
data/cldr/collation/*.xml (CLDR 46).  cldr_tailor applies each locale's
rules; dfa_pool builds and compresses the machines.

CE index 0 means "not in DUCET -- use implicit weights".  Root's CE
sequences are numbered from 1 in allkeys.txt order; sequences only a
tailoring uses follow.

Collation elements are packed into a uint32_t:

  bits 31-16   primary   (16 bits)
  bits 15-7    secondary ( 9 bits)
  bits 6-0     tertiary  ( 7 bits)

There is no variable flag: nothing reads one (libutf's variable weighting is
non-ignorable), and keeping it cost the primary its top bit.  Masked to 15
bits, the implicit trail weight 0x8000 -- U+8000, U+20000, U+28000, U+30000
-- became 0, an ignorable, and those ideographs sorted against whatever came
next.  Whether a CE is variable is a property of its primary's range, if
alternate shifted is ever wanted.  Respaced regular primaries stay below
0x8000, where the trails begin.

Locale settings that are not table data are compiled into each collator:
[reorder] as primary ranges to shift, [caseFirst upper] as a tertiary map,
[backwards 2] as a flag.  The Latin fast-path tables have them applied
already.
"""
import collections
import os
import re
import sys

import cldr_tailor as ct
import dfa_pool

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, 'data')
TABLES = os.path.join(HERE, '..', 'tables')
HEADER = os.path.join(HERE, '..', 'include', 'utf', 'utf_tables.h')

SECONDARY_BITS = 9
TERTIARY_BITS = 7
PRIMARY_CAP = 0x8000    # implicit trail weights start here
LATIN_LIMIT = 0x180     # U+0000..U+017F: Basic Latin through Latin Extended-A
BACKWARD_SECONDARY = 1  # UTF_COLLATOR_BACKWARD_SECONDARY
HAS_SETTINGS = 2        # UTF_COLLATOR_HAS_SETTINGS: a reorder or tertiary map

# The European locales with CLDR 46 collation data.  Those with no rules of
# their own (de, en, fr, ...) are listed anyway: utf_collator_find should
# know them, and they cost nothing, since they share root's machines.
LOCALES = """
    az be bg br bs ca cs cy da de de_AT dsb el en eo es et fi fo fr fr_CA fy
    ga gl hr hsb hu is it kl lb lt lv mk mt nb nl nn no pl pt ro ru se sk sl
    smn sq sr sr_Latn sv tr uk
""".split()

# [reorder] codes in these locales -> Scripts.txt names.
SCRIPTS = {'Latn': 'Latin', 'Cyrl': 'Cyrillic', 'Grek': 'Greek'}

HEADER_BEGIN = '/* ---- DUCET collation (generated by gen/gen_ducet.py; do not edit) ---- */'
HEADER_END = '/* ---- end of DUCET collation ---- */'


def utf8(cp):
    return chr(cp).encode('utf-8', 'surrogatepass')


def parse_scripts():
    script = {}
    for line in open(os.path.join(DATA, 'Scripts.txt'), encoding='utf-8'):
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        rng, name = (x.strip() for x in line.split(';'))
        lo, _, hi = rng.partition('..')
        for cp in range(int(lo, 16), int(hi or lo, 16) + 1):
            script[cp] = name
    return script


class Weights:
    """The respaced weight space: root maps shared by every collator, plus
    each locale's own new weights."""

    def __init__(self, locales):
        regular = [v for v in ct.LEVEL_VALUES[0] if v <= ct.REGULAR_MAX]
        self.maps = [ct.respace(locales, 0, regular, PRIMARY_CAP),
                     ct.respace(locales, 1, ct.LEVEL_VALUES[1], 1 << SECONDARY_BITS),
                     ct.respace(locales, 2, ct.LEVEL_VALUES[2], 1 << TERTIARY_BITS)]

    def level(self, lvl, x, loc):
        if loc is not None and x in loc.local[lvl]:
            return loc.local[lvl][x]
        if x in self.maps[lvl]:
            return self.maps[lvl][x]
        if lvl == 0 and x > ct.REGULAR_MAX and x == int(x):
            return int(x)               # implicit leads and trails stay put
        raise ValueError('no respaced weight for %s at level %d' % (x, lvl + 1))

    def pack(self, ce, loc=None):
        p, s, t, _ = ce
        hi = self.level(0, p, loc)
        if hi > 0xFFFF:
            raise ValueError('primary %#x does not fit 16 bits' % hi)
        return (hi << 16) | (self.level(1, s, loc) << TERTIARY_BITS) | self.level(2, t, loc)


def secondary(ce):
    return (ce >> TERTIARY_BITS) & ((1 << SECONDARY_BITS) - 1)


def reorder_ranges(codes, w, script_of):
    """[reorder] as primary ranges to shift: (lo, hi, delta) triples.

    A script's group runs from its first primary to the next script's first,
    as in CLDR; everything below the first script (spaces, punctuation,
    symbols, currency, digits) stays put, the named scripts follow it in
    order, then the rest in root order.  A group begins at the script's
    first letter.  Only a lead CE (one with a secondary) is remapped, so
    implicit trail weights are never touched."""
    first = {}
    for cp, ces in ct.ROOT_SINGLES.items():
        name = script_of.get(cp)
        p, _, _, var = ces[0]
        if name in (None, 'Common', 'Inherited', 'Unknown') or var or not p or p > ct.REGULAR_MAX:
            continue
        if ct.category(cp) not in ('Lu', 'Ll', 'Lt', 'Lo'):
            continue        # symbols and modifier letters sit among the symbols
        mp = w.maps[0][p]
        first[name] = min(first.get(name, mp), mp)
    groups = sorted((p, name) for name, p in first.items())
    bounds = {name: (p, (groups[i + 1][0] if i + 1 < len(groups) else PRIMARY_CAP) - 1)
              for i, (p, name) in enumerate(groups)}
    wanted = []
    for code in codes:
        if code not in SCRIPTS or SCRIPTS[code] not in bounds:
            raise ValueError('unsupported reorder code %s' % code)
        wanted.append(SCRIPTS[code])
    order = wanted + [name for _, name in groups if name not in wanted]
    cursor, ranges = groups[0][0], []
    for name in order:
        lo, hi = bounds[name]
        if cursor != lo:
            ranges.append((lo, hi, cursor - lo))
        cursor += hi - lo + 1
    ranges.sort()
    merged = []
    for lo, hi, d in ranges:            # adjacent groups moving together
        if merged and merged[-1][1] + 1 == lo and merged[-1][2] == d:
            merged[-1] = (merged[-1][0], hi, d)
        else:
            merged.append((lo, hi, d))
    return merged


def case_first_upper(loc, w):
    """[caseFirst upper] as a tertiary map: upper case before mixed before
    lower (uncased counts as lower), keeping order within each.  A root
    tertiary's case is its letters' majority; a tailored one's is that of
    the character the rules gave it."""
    votes = collections.defaultdict(collections.Counter)
    for key, ces in ct.ROOT.items():
        if len(key) != 1:
            continue
        cls = {'Lu': 0, 'Lt': 1, 'Ll': 2}.get(ct.category(key[0]))
        if cls is None:
            continue
        for ce in ces:
            if ce[0] and ce[2]:
                votes[w.maps[2][ce[2]]][cls] += 1

    def root_class(t):
        v = votes.get(t)
        return max(v, key=lambda c: (v[c], c)) if v else 2
    cls = {t: root_class(t) for t in w.maps[2].values() if t}
    for frac, t in loc.local[2].items():
        cls[t] = string_case(loc.tertiary_item[frac])
    tmap = [0] * (1 << TERTIARY_BITS)
    for i, t in enumerate(sorted(cls, key=lambda t: (cls[t], t)), 1):
        tmap[t] = i
    return tmap


def string_case(cps):
    """0 upper, 1 mixed, 2 lower, as ICU classes a tailored string: by all
    its cased characters ("AA" upper, "Aa" mixed); uncased counts as lower."""
    cats = {ct.category(c) for c in ct.nfd(cps)}
    upper = bool(cats & {'Lu', 'Lt'})
    lower = 'Ll' in cats
    return 1 if upper and lower else 0 if upper else 2


def settle(ce, coll):
    """A packed CE as a collator compares it: reordered, case-mapped."""
    p = ce >> 16
    if secondary(ce):
        for lo, hi, d in coll['reorder']:
            if lo <= p <= hi:
                ce = (ce & 0xFFFF) | ((p + d) << 16)
                break
    if coll['tmap'] is not None:
        ce = (ce & ~((1 << TERTIARY_BITS) - 1)) | coll['tmap'][ce & ((1 << TERTIARY_BITS) - 1)]
    return ce


def c_array(ctype, name, size, values, per_line, fmt):
    lines = ['const %s %s[%s] =\n{\n' % (ctype, name, size)]
    for i in range(0, len(values), per_line):
        row = ','.join(fmt % v for v in values[i:i + per_line])
        lines.append('    %s%s\n' % (row, ',' if i + per_line < len(values) else ''))
    lines.append('};\n\n')
    return ''.join(lines)


def main():
    script_of = parse_scripts()
    locales = [ct.load_locale(name) for name in LOCALES]
    for loc in locales:
        if loc.unsupported:
            sys.exit('%s: unsupported rules %s' % (loc.name, dict(loc.unsupported)))
    w = Weights(locales)

    # CE sequences: root's in allkeys order, keyed by their raw CEs as before;
    # then each new packed sequence a tailoring uses, deduplicated.
    seq_index = {}
    for ces in ct.ROOT.values():
        seq_index.setdefault(ces, len(seq_index) + 1)
    packed = [None] + [tuple(w.pack(ce) for ce in ces) for ces in seq_index]
    index_of_packed = {}
    for i in range(1, len(packed)):
        index_of_packed.setdefault(packed[i], i)

    def index_of(ces, loc):
        key = tuple(w.pack(ce, loc) for ce in ces)
        if key not in index_of_packed:
            index_of_packed[key] = len(packed)
            packed.append(key)
        return index_of_packed[key]

    root_singles = {k[0]: seq_index[v] for k, v in ct.ROOT.items() if len(k) == 1}
    root_pairs = {k: seq_index[v] for k, v in ct.ROOT.items() if len(k) == 2}
    root_longer = {k: seq_index[v] for k, v in ct.ROOT.items() if len(k) > 2}

    collators = []
    for loc in [None] + locales:
        sup = loc.suppressed if loc else set()
        coll = dict(name=loc.name if loc else 'root', loc=loc,
                    singles=dict(root_singles),
                    pairs={k: v for k, v in root_pairs.items() if k[0] not in sup},
                    longer={k: v for k, v in root_longer.items() if k[0] not in sup},
                    reorder=[], tmap=None, flags=0)
        if loc:
            for key, ces in sorted(loc.map.items()):
                idx = index_of(ces, loc)
                {1: coll['singles'], 2: coll['pairs']}.get(len(key), coll['longer'])[
                    key[0] if len(key) == 1 else key] = idx
            for s in loc.settings:
                word, *args = s.split()
                if word == 'reorder':
                    coll['reorder'] = reorder_ranges(args, w, script_of)
                elif s == 'caseFirst upper':
                    coll['tmap'] = case_first_upper(loc, w)
                elif s == 'backwards 2':
                    coll['flags'] |= BACKWARD_SECONDARY
                elif s == 'normalization on':
                    pass    # canonical closure already covers tailored strings
                else:
                    sys.exit('%s: unsupported setting [%s]' % (loc.name, s))
        if coll['reorder'] or coll['tmap'] is not None:
            coll['flags'] |= HAS_SETTINGS
        starters = {k[0] for k in coll['pairs']} | {k[0] for k in coll['longer']}
        latin, starter = [0] * LATIN_LIMIT, [0] * LATIN_LIMIT
        for cp in range(LATIN_LIMIT):
            idx = coll['singles'].get(cp)
            if idx is None or len(packed[idx]) != 1 or packed[idx][0] == 0:
                continue
            (starter if cp in starters else latin)[cp] = settle(packed[idx][0], coll)
        coll['latin'], coll['latin_starter'] = tuple(latin), tuple(starter)
        # Lead bytes that can begin one of this collator's contractions: the
        # slow path looks for a contraction only behind one of these.
        leads = [0] * 32
        for cp in starters:
            b = utf8(cp)[0]
            leads[b >> 3] |= 1 << (b & 7)
        coll['leads'] = tuple(leads)
        collators.append(coll)

    # The shared pools.  Pair results go through a side table, as pairs.cpp
    # built it: slot -> CE index, root's slots first in code point order.
    singles_pool, pairs_pool = dfa_pool.Pool(), dfa_pool.Pool()
    slots = {}
    for k in sorted(root_pairs):
        slots.setdefault(root_pairs[k], len(slots) + 1)
    for coll in collators:
        for k in sorted(coll['pairs']):
            slots.setdefault(coll['pairs'][k], len(slots) + 1)
    for coll in collators:
        singles_pool.add(coll['name'], [(utf8(cp), v) for cp, v in sorted(coll['singles'].items())])
        pairs_pool.add(coll['name'], [(utf8(a) + utf8(b), slots[v])
                                      for (a, b), v in sorted(coll['pairs'].items())])
    st, pt = singles_pool.emit(), pairs_pool.emit()
    for tables, what in ((st, 'tr_ducet'), (pt, 'tr_ducet_contract')):
        if tables['nstates'] + tables['max_value'] >= 1 << 16 or len(tables['sbt']) >= 1 << 16:
            sys.exit('%s no longer fits unsigned short' % what)

    # Check the emitted machines, the way collate.c reads them: all of root,
    # and every entry a locale changed.
    root_s, root_p = st['starts']['root'], pt['starts']['root']
    for coll in collators:
        s0, p0 = st['starts'][coll['name']], pt['starts'][coll['name']]
        check_all = coll['name'] == 'root'
        for cp, v in coll['singles'].items():
            if (check_all or root_singles.get(cp) != v) and dfa_pool.run(st, s0, utf8(cp)) != v:
                sys.exit('%s: U+%04X reads back wrong' % (coll['name'], cp))
        for (a, b), v in coll['pairs'].items():
            if (check_all or root_pairs.get((a, b)) != v) and \
                    dfa_pool.run(pt, p0, utf8(a) + utf8(b)) != slots[v]:
                sys.exit('%s: U+%04X U+%04X reads back wrong' % (coll['name'], a, b))
        for (a, b) in root_pairs:
            if (a, b) not in coll['pairs'] and dfa_pool.run(pt, p0, utf8(a) + utf8(b)) not in (0, None):
                sys.exit('%s: suppressed U+%04X U+%04X still contracts' % (coll['name'], a, b))

    offsets, weights = [0], []
    for seq in packed[1:]:
        offsets.append(len(weights))
        weights.extend(seq)
    offsets.append(len(weights))
    if offsets[-1] > 0xFFFF:
        sys.exit('ducet_ce_offset no longer fits unsigned short')
    common_s = w.maps[1][ct.COMMON_S]
    common_t = w.maps[2][ct.COMMON_T]

    # Root-only inputs for the C++ builders, unchanged by any tailoring.
    with open(os.path.join(DATA, 'tr_ducet.txt'), 'w') as f:
        for cp, idx in sorted(root_singles.items()):
            f.write('%04X;%d\n' % (cp, idx))
    with open(os.path.join(DATA, 'tr_ducet_contract.txt'), 'w') as f:
        for (a, b), idx in sorted(root_pairs.items()):
            f.write('%04X %04X;%04X\n' % (a, b, idx))

    write_dfa_tables(st, pt, slots, len(collators))
    write_cetable(offsets, weights, collators, st, pt, common_s, common_t)
    write_header(st, pt, slots, len(packed) - 1, offsets, collators, common_s, common_t)

    print('%d collators; tr_ducet %d states, %d sbt; tr_ducet_contract %d states, '
          '%d sbt; %d CE sequences (%d from tailorings), %d CEs'
          % (len(collators), st['nstates'], len(st['sbt']), pt['nstates'], len(pt['sbt']),
             len(packed) - 1, len(packed) - len(seq_index) - 1, len(weights)), file=sys.stderr)


def write_dfa_tables(st, pt, slots, ncollators):
    out = ['/* ducet_dfa_tables.c -- DUCET collation DFAs.\n'
           ' *\n'
           ' * Generated by gen/gen_ducet.py.  DO NOT EDIT -- regenerate with:\n'
           ' *   python3 gen/gen_ducet.py\n'
           ' *\n'
           ' * Each table is one shared pool of %d collators\' machines; see the\n'
           ' * collator registry in ducet_cetable.c for their start states.\n'
           ' */\n'
           '#include "utf/utf_tables.h"\n\n' % ncollators]
    for t, name in ((st, 'tr_ducet'), (pt, 'tr_ducet_contract')):
        out.append('/* %d states, %d columns, %d sbt entries */\n'
                   % (t['nstates'], max(t['itt']) + 1, len(t['sbt'])))
        out.append(c_array('unsigned char', name + '_itt', 256, t['itt'], 16, '%3d'))
        out.append(c_array('unsigned short', name + '_sot', t['nstates'], t['sot'], 16, '%5d'))
        out.append(c_array('unsigned short', name + '_sbt', len(t['sbt']), t['sbt'], 16, '%5d'))
    side = [0] + [idx for idx, _ in sorted(slots.items(), key=lambda kv: kv[1])]
    out.append('/* tr_ducet_contract accepting state N + slot -> CE index; slot 0 is\n'
               ' * "no contraction". */\n')
    out.append(c_array('uint32_t', 'tr_ducet_contract_nfc_compose_result', len(side), side, 8, '%6d'))
    with open(os.path.join(TABLES, 'ducet_dfa_tables.c'), 'w') as f:
        f.write(''.join(out).rstrip('\n') + '\n')


def write_cetable(offsets, weights, collators, st, pt, common_s, common_t):
    out = ['/* ducet_cetable.c -- DUCET CE weights and the collator registry.\n'
           ' *\n'
           ' * Generated by gen/gen_ducet.py from gen/data/allkeys.txt (Unicode 16.0)\n'
           ' * and CLDR 46 collation rules.  DO NOT EDIT -- regenerate with:\n'
           ' *   python3 gen/gen_ducet.py\n'
           ' *\n'
           ' * CE index 0 = sentinel (use implicit weights).\n'
           ' */\n'
           '#include "utf/utf_tables.h"\n\n'
           '/* The reader in collate.c unpacks with utf_tables.h\'s layout and builds\n'
           ' * implicit CEs from its common weights; both must match what was packed. */\n']
    out.append('_Static_assert(DUCET_CE_PRIMARY_SHIFT == 16, "CE layout changed");\n')
    out.append('_Static_assert(DUCET_CE_SECONDARY_SHIFT == %d, "CE layout changed");\n' % TERTIARY_BITS)
    out.append('_Static_assert(DUCET_CE_SECONDARY_MASK == 0x%X, "CE layout changed");\n'
               % ((1 << SECONDARY_BITS) - 1))
    out.append('_Static_assert(DUCET_CE_TERTIARY_MASK == 0x%X, "CE layout changed");\n'
               % ((1 << TERTIARY_BITS) - 1))
    out.append('_Static_assert(DUCET_COMMON_SECONDARY == 0x%04X, "common secondary moved");\n' % common_s)
    out.append('_Static_assert(DUCET_COMMON_TERTIARY == 0x%02X, "common tertiary moved");\n\n' % common_t)

    out.append('/* ducet_ce_offset[i] is where CE sequence i starts in ducet_ce_weights;\n'
               ' * it has ducet_ce_offset[i+1] - ducet_ce_offset[i] CEs. */\n')
    out.append(c_array('unsigned short', 'ducet_ce_offset', len(offsets), offsets, 16, '%5d'))
    out.append('/* Packed CE weights; layout in utf_tables.h (DUCET_CE_*). */\n')
    out.append(c_array('uint32_t', 'ducet_ce_weights', len(weights), weights, 8, '0x%08X'))

    # Per-collator data, each distinct table emitted once.
    def dedupe(key, emit):
        names = {}
        for coll in collators:
            data = coll[key]
            if data not in names:
                names[data] = emit(data, len(names))
            coll[key + '_c'] = names[data]

    contractions = []
    for coll in collators:
        coll['longer_t'] = tuple(sorted(((k, v) for k, v in coll['longer'].items()),
                                        key=lambda kv: (kv[0][0], -len(kv[0]), kv[0])))

    def emit_longer(data, i):
        if not data:
            return ('NULL', 0)
        name = 'ducet_contractions_%d' % i
        rows = ['    { { %s }, %d, %d },\n' % (', '.join('0x%04X' % c for c in k + (0,) * (4 - len(k))),
                                                 len(k), v) for k, v in data]
        contractions.append('static const utf_ducet_contraction %s[%d] =\n{\n%s};\n\n'
                            % (name, len(data), ''.join(rows)))
        return (name, len(data))
    dedupe('longer_t', emit_longer)
    out.append('/* Contractions of three or four code points, by first code point and\n'
               ' * longest first, so the first match is the one to take. */\n')
    out.extend(contractions)

    latin_tables = []

    def emit_latin(data, i):
        name = 'ducet_latin_%d' % len(latin_tables)     # one numbering for both kinds
        latin_tables.append('static ' + c_array('uint32_t', name, 'DUCET_LATIN_LIMIT', data, 8, '0x%08X'))
        return name
    dedupe('latin', emit_latin)
    dedupe('latin_starter', emit_latin)


    out.append('/* Latin fast path, U+0000..U+017F: the CE of each code point that has\n'
               ' * exactly one, else 0, with the collator\'s reorder and case map applied.\n'
               ' * A code point that can start a contraction is 0 in a collator\'s first\n'
               ' * table and has its CE in the second, good only when no contraction\n'
               ' * follows it. */\n')
    out.extend(latin_tables)

    out.append('_Static_assert(DUCET_LATIN_LIMIT == 0x%X, "Latin range changed");\n\n' % LATIN_LIMIT)

    reorders, tmaps = [], []
    for coll in collators:
        coll['reorder_t'] = tuple(coll['reorder'])
        coll['tmap_t'] = tuple(coll['tmap']) if coll['tmap'] else None

    def emit_reorder(data, i):
        if not data:
            return ('NULL', 0)
        name = 'ducet_reorder_%d' % i
        reorders.append('static const utf_ducet_reorder %s[%d] =\n{\n%s};\n\n' % (
            name, len(data), ''.join('    { 0x%04X, 0x%04X, %d },\n' % r for r in data)))
        return (name, len(data))
    dedupe('reorder_t', emit_reorder)

    def emit_tmap(data, i):
        if data is None:
            return 'NULL'
        name = 'ducet_tertiary_%d' % i
        tmaps.append('static ' + c_array('unsigned char', name, 'DUCET_CE_TERTIARY_MASK + 1',
                                         data, 16, '%3d'))
        return name
    dedupe('tmap_t', emit_tmap)
    out.append('/* [reorder]: primaries in [lo, hi] move by delta.  Only lead CEs (those\n'
               ' * with a secondary) are remapped; implicit trail weights never are. */\n')
    out.extend(reorders)
    out.append('/* [caseFirst upper]: tertiary weight -> weight ordering upper case first. */\n')
    out.extend(tmaps)

    out.append('/* Collators: each a view of the shared tables -- its start states in\n'
               ' * the DFAs, its longer contractions, its Latin fast-path tables and its\n'
               ' * settings.  utf_collators[0] is root; utf_collator_find searches by name. */\n')
    out.append('const struct utf_collator utf_collators[UTF_COLLATOR_COUNT] =\n{\n')
    for coll in collators:
        (lname, nlong), (rname, nre) = coll['longer_t_c'], coll['reorder_t_c']
        leads = '{ %s }' % ', '.join('0x%02X' % b for b in coll['leads'])
        out.append('    { "%s", %d, %d,\n      %s,\n      %s, %d, %s, %s, %s, %d, %s, %s },\n' % (
            coll['name'], st['starts'][coll['name']], pt['starts'][coll['name']], leads,
            lname, nlong, coll['latin_c'], coll['latin_starter_c'], rname, nre,
            coll['tmap_t_c'], ' | '.join(n for bit, n in ((BACKWARD_SECONDARY, 'UTF_COLLATOR_BACKWARD_SECONDARY'),
                                                         (HAS_SETTINGS, 'UTF_COLLATOR_HAS_SETTINGS'))
                                        if coll['flags'] & bit) or '0'))
    out.append('};\n')
    with open(os.path.join(TABLES, 'ducet_cetable.c'), 'w') as f:
        f.write(''.join(out))


def write_header(st, pt, slots, nseq, offsets, collators, common_s, common_t):
    h = [HEADER_BEGIN, '''
/* tr_ducet: code point -> CE index; tr_ducet_contract: two code points ->
 * contraction slot (tr_ducet_contract_nfc_compose_result maps it to a CE
 * index).  Each is one pool holding every collator's machine; a collator
 * names its start states.  The START_STATE macros are root's. */''']
    for t, up, low in ((st, 'TR_DUCET', 'tr_ducet'), (pt, 'TR_DUCET_CONTRACT', 'tr_ducet_contract')):
        h.append('#define %s_START_STATE (%d)' % (up, t['starts']['root']))
        h.append('#define %s_ACCEPTING_STATES_START (%d)' % (up, t['nstates']))
        h.append('extern UTF_API const unsigned char  %s_itt[256];' % low)
        h.append('extern UTF_API const unsigned short %s_sot[%d];' % (low, t['nstates']))
        h.append('extern UTF_API const unsigned short %s_sbt[%d];' % (low, len(t['sbt'])))
    h.append('#define TR_DUCET_CONTRACT_NFC_COMPOSE_RESULTS (%d)' % len(slots))
    h.append('extern UTF_API const uint32_t tr_ducet_contract_nfc_compose_result[%d];' % (len(slots) + 1))
    h.append('''
/* A CE is a uint32_t:  bits 31-16 primary, bits 15-7 secondary, bits 6-0
 * tertiary.  There is no variable flag; libutf's variable weighting is
 * non-ignorable.  ducet_cetable.c asserts this layout against what the
 * generator packed. */
#define DUCET_CE_PRIMARY_SHIFT   16
#define DUCET_CE_SECONDARY_SHIFT %d
#define DUCET_CE_SECONDARY_MASK  0x%X
#define DUCET_CE_TERTIARY_MASK   0x%X
#define DUCET_COMMON_SECONDARY   0x%04X
#define DUCET_COMMON_TERTIARY    0x%02X
#define DUCET_CE_SEQUENCES %d
extern const unsigned short ducet_ce_offset[%d];
extern const uint32_t ducet_ce_weights[];

/* A contraction of three or four code points. */
typedef struct {
    uint32_t cp[4];
    unsigned char n;
    unsigned short ce_index;
} utf_ducet_contraction;

/* [reorder]: primaries in [lo, hi] move by delta. */
typedef struct {
    unsigned short lo, hi;
    short delta;
} utf_ducet_reorder;

#define DUCET_LATIN_LIMIT 0x%X
#define UTF_COLLATOR_BACKWARD_SECONDARY %d
#define UTF_COLLATOR_HAS_SETTINGS       %d   /* reorder or tertiary_map: the
                                               slow path must apply them */

/* A collator is one locale's view of the shared DUCET tables: where it
 * starts in each DFA, its longer contractions, its Latin fast-path tables
 * (DUCET_LATIN_LIMIT entries each; a code point that can start a
 * contraction has its CE in latin_starter_ce, good only when none follows),
 * and the settings CLDR gives it.  collate.h hands it out as an opaque
 * utf_collator.  utf_collators[0] is root. */
struct utf_collator {
    const char *name;
    int ducet_start;                    /* start state in tr_ducet */
    int contract_start;                 /* start state in tr_ducet_contract */
    unsigned char contract_leads[32];   /* lead bytes that can begin a
                                           contraction, as a bit set; kept
                                           inline, one load from the gate */
    const utf_ducet_contraction *contractions;  /* by cp[0], longest first */
    int n_contractions;
    const uint32_t *latin_ce;
    const uint32_t *latin_starter_ce;
    const utf_ducet_reorder *reorder;   /* [reorder], applied to lead CEs */
    int n_reorder;
    const unsigned char *tertiary_map;  /* [caseFirst upper], or NULL */
    int flags;                          /* UTF_COLLATOR_* */
};
#define UTF_COLLATOR_COUNT %d
extern const struct utf_collator utf_collators[UTF_COLLATOR_COUNT];
''' % (TERTIARY_BITS, (1 << SECONDARY_BITS) - 1, (1 << TERTIARY_BITS) - 1, common_s, common_t,
       nseq, len(offsets), LATIN_LIMIT, BACKWARD_SECONDARY, HAS_SETTINGS, len(collators)))
    h.append(HEADER_END)
    block = '\n'.join(h)

    text = open(HEADER, encoding='utf-8').read()
    if HEADER_BEGIN in text:
        i = text.index(HEADER_BEGIN)
        j = text.index(HEADER_END) + len(HEADER_END)
    else:                               # first run: the hand-kept DUCET section
        i = text.index('/* ---- DUCET collation DFAs ---- */')
        j = text.index('/* ---- Charset approximation DFAs ---- */')
        block += '\n\n'
    with open(HEADER, 'w', encoding='utf-8') as f:
        f.write(text[:i] + block + text[j:])


